const { chromium } = require('/Users/zhangfei/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:4174/?screen=study&dict=fr&view=list');
  await page.waitForSelector('.word-row');
  await page.screenshot({path:path.join(__dirname,'vocabulary-list.png')});
  await page.selectOption('#book-switcher','grammar-fr');
  if(await page.locator('#study-kind-switch').count()) throw Error('Removed mode toggle remains');
  if(await page.locator('#book-switcher option').count()!==6) throw Error('Books missing');
  if(await page.locator('#book-switcher option[value=fr]').textContent()!=='Français Mots') throw Error('Wrong French book title');
  await page.waitForSelector('.word-row');
  if(await page.locator('.word-row').count()!==6) throw Error('Grammar catalog not loaded');
  await page.locator('[data-detail]').first().click();
  await page.waitForSelector('#entry-detail-dialog[open]');
  if(await page.locator('#entry-detail-dialog .example-translation').count()) throw Error('Detail translations remain');
  await page.screenshot({path:path.join(__dirname,'grammar-detail.png')});
  await page.keyboard.press('Escape');
  if(await page.locator('#entry-detail-dialog').evaluate(el=>el.open)) throw Error('Escape failed');
  if(!await page.locator('[data-detail]').first().evaluate(el=>el===document.activeElement)) throw Error('Detail focus restoration failed');
  await page.click('#card-view');
  await page.click('#reveal-button');
  await page.screenshot({path:path.join(__dirname,'grammar-card.png')});
  if(await page.locator('.card-examples .example-translation').count()) throw Error('Card translations remain');
  const exampleCount = await page.locator('.card-examples .entry-example').count();
  if(exampleCount!==2) throw Error('Expected two card examples');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#book-switcher').focus();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  await page.selectOption('#book-switcher','grammar-fr');
  await page.click('#reveal-button');
  await page.screenshot({path:path.join(__dirname,'grammar-card-mobile.png'),fullPage:true});
  await page.click('#list-view');
  await page.screenshot({path:path.join(__dirname,'grammar-list-mobile.png'),fullPage:true});
  await page.locator('[data-detail]').first().click();
  await page.screenshot({path:path.join(__dirname,'grammar-detail-mobile.png')});
  await page.click('#close-entry-detail');
  await page.setViewportSize({width:320,height:740});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  if(overflow) throw Error('Horizontal overflow at 320px');
  await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
  await page.screenshot({path:path.join(__dirname,'grammar-list-dark.png')});
  await page.click('#search-toggle');
  await page.fill('#search-input','zzzzzz-no-match');
  await page.waitForSelector('.empty-state');
  await page.click('#clear-search');
  await page.waitForSelector('.word-row');
  await page.selectOption('#book-switcher','fr');
  await page.waitForSelector('.word-row');
  if(await page.inputValue('#book-switcher')!=='fr') throw Error('Book restoration failed');
  if(await page.locator('.example-translation').count()) throw Error('Example translations remain');
  if(errors.length) throw Error(errors.join('\n'));
  fs.writeFileSync(path.join(__dirname,'browser-result.json'),JSON.stringify({success:true,exampleCount,errors,viewports:[1440,390,320],checks:['all-book selection and titles','original-language examples','detail open/Escape/focus','card reveal','narrow layout','dark and reduced motion','no results and clear']},null,2));
  await browser.close();
  console.log('Browser workflow checks passed.');
})().catch(e=>{console.error(e);process.exit(1)});
