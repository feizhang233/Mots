const { chromium } = require('/Users/zhangfei/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const origin = 'http://127.0.0.1:4181/';
    await page.goto(origin + '?screen=study&dict=grammar-fr&view=list');
    assert.equal(await page.locator('[data-grammar-group]').count(), 3);
    assert.equal(await page.locator('#category-nav [data-sub]').count(), 0);
    assert.equal(await page.locator('[data-grammar-group][open]').count(), 0);
    const first = page.locator('[data-grammar-group="g1.01"]');
    await first.locator('summary').focus();
    await page.keyboard.press('Enter');
    await page.waitForSelector('[data-grammar-group="g1.01"][open]');
    await first.locator('[data-rate="2"]').first().click();
    assert.equal(await first.evaluate(el => el.open), true);
    assert.equal(await first.locator('[data-rate="2"]').first().getAttribute('aria-pressed'), 'true');
    assert.equal(await first.locator('[data-rate="2"]').first().evaluate(el => el === document.activeElement), true);
    await first.locator('[data-detail]').first().click();
    await page.waitForSelector('#entry-detail-dialog[open]');
    await page.keyboard.press('Escape');
    assert.equal(await first.locator('[data-detail]').first().evaluate(el => el === document.activeElement), true);
    await page.screenshot({ path: path.join(__dirname, 'grouped-desktop.png') });
    await page.click('#card-view');
    assert.equal(await page.locator('.flashcard').count(), 1);
    assert.equal(await page.locator('[data-grammar-group]').count(), 0);
    await page.click('#next-word');
    const card = await page.locator('.french-word').textContent();
    await page.click('#list-view');
    assert.equal(await first.evaluate(el => el.open), true);
    await page.click('#card-view');
    assert.equal(await page.locator('.french-word').textContent(), card);
    await page.click('#list-view');
    await page.click('#settings-button');
    await page.locator('#settings-learning > summary').click();
    assert.equal(await page.inputValue('#grammar-grouping'), 'true');
    await page.selectOption('#grammar-grouping', 'false');
    await page.click('#close-settings');
    assert.equal(await page.locator('[data-grammar-group]').count(), 0);
    assert.equal(await page.locator('.word-row').count(), 6);
    assert.ok(await page.locator('#category-nav [data-sub]').count() > 0);
    await page.reload();
    assert.equal(await page.locator('[data-grammar-group]').count(), 0);
    await page.selectOption('#book-switcher', 'grammar-de');
    assert.equal(await page.locator('[data-grammar-group]').count(), 3);
    await page.selectOption('#book-switcher', 'grammar-fr');
    assert.equal(await page.locator('[data-grammar-group]').count(), 0);
    await page.click('#settings-button');
    await page.locator('#settings-learning > summary').click();
    await page.selectOption('#grammar-grouping', 'true');
    await page.locator('#grammar-grouping').focus();
    await page.keyboard.press('Space');
    await page.screenshot({ path: path.join(__dirname, 'settings-select.png') });
    await page.keyboard.press('Escape');
    if (await page.locator('#settings-dialog').evaluate(el => el.open)) await page.click('#close-settings');
    await page.click('#search-toggle');
    await page.fill('#search-input', 'il y a');
    assert.equal(await page.locator('[data-grammar-group][open]').count(), 1);
    assert.equal(await page.locator('.word-row').count(), 1);
    await page.fill('#search-input', 'zzzz-no-match');
    await page.waitForSelector('.empty-state');
    await page.click('#clear-search');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(__dirname, 'grouped-mobile.png'), fullPage: true });
    await page.click('#category-picker');
    assert.equal(await page.locator('#mobile-category-nav [data-sub]').count(), 0);
    await page.locator('#mobile-category-nav [data-category="g2"]').click();
    assert.equal(await page.locator('#category-dialog').evaluate(el => el.open), false);
    assert.equal(await page.locator('[data-grammar-group]').count(), 1);
    await page.locator('[data-grammar-group] > summary').click();
    await page.setViewportSize({ width: 320, height: 740 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
    await page.screenshot({ path: path.join(__dirname, 'grouped-mobile-dark.png'), fullPage: true });
    await page.selectOption('#book-switcher', 'fr');
    assert.equal(await page.locator('[data-grammar-group]').count(), 0);
    await page.click('#settings-button');
    await page.locator('#settings-learning > summary').click();
    assert.equal(await page.locator('#grammar-grouping-field').isVisible(), false);
    await page.click('#close-settings');
    // Removing a group's final visible card must focus the next visible heading.
    const focusContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const focusPage = await focusContext.newPage();
    focusPage.on('pageerror', e => errors.push(e.message));
    await focusPage.goto(origin + '?screen=study&dict=grammar-fr&view=list&hide=3');
    await focusPage.locator('[data-grammar-group="g1.01"] > summary').click();
    await focusPage.locator('[data-grammar-group="g1.01"] [data-rate="3"]').first().click();
    await focusPage.locator('[data-grammar-group="g1.01"] [data-rate="3"]').first().click();
    assert.equal(await focusPage.locator('[data-grammar-group="g1.01"]').count(), 0);
    assert.equal(await focusPage.locator('[data-grammar-group="g2.01"] > summary').evaluate(el => el === document.activeElement), true);
    await focusPage.locator('[data-grammar-group="g2.01"] > summary').click();
    await focusPage.locator('[data-grammar-group="g2.01"] [data-delete]').first().click();
    await focusPage.locator('[data-grammar-group="g2.01"] [data-delete]').first().click();
    assert.equal(await focusPage.locator('[data-grammar-group="g3.01"] > summary').evaluate(el => el === document.activeElement), true);
    await focusPage.click('#undo-deletion');
    assert.equal(await focusPage.locator('[data-grammar-group="g2.01"]').count(), 1);
    const touchContext = await browser.newContext({ viewport: { width: 320, height: 740 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
    const touchPage = await touchContext.newPage();
    touchPage.on('pageerror', e => errors.push(e.message));
    await touchPage.goto(origin + '?screen=study&dict=grammar-fr&view=list');
    await touchPage.locator('[data-grammar-group="g1.01"] > summary').tap();
    assert.equal(await touchPage.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.equal(await touchPage.locator('[data-grammar-group="g1.01"] > summary').evaluate(el => getComputedStyle(el).borderTopLeftRadius), '28px');
    const target = await touchPage.locator('[data-grammar-group="g1.01"] [data-rate]').first().boundingBox();
    assert.ok(target.width >= 44 && target.height >= 44);
    await touchPage.locator('.rating-legend').tap();
    await touchPage.screenshot({ path: path.join(__dirname, 'grouped-touch-320.png'), fullPage: true, animations: 'disabled' });
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(__dirname, 'browser-result.json'), JSON.stringify({ success: true, errors, viewports: [1440, 390, 320], checks: ['keyboard disclosure', 'rating persistence and focus', 'detail Escape/focus', 'small flashcards and resume', 'per-book has/none reload', 'native select', 'search and empty state', 'mobile first-level category drawer', 'dark/reduced motion', 'rating/deletion last-child focus and undo', 'vocabulary unchanged'] }, null, 2));
    console.log('Grammar grouping browser checks passed.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
