#!/usr/bin/env python3
"""Validate the N2 snapshot and stable identities, then reproduce its browser book."""
from pathlib import Path
import argparse,json,re
ROOT=Path(__file__).resolve().parent.parent
SOURCE=ROOT/'database/japanese/hongbao-n2/vocabulary.json'
IDENTITIES=ROOT/'database/japanese/hongbao-n2/identity.json'
TARGET=ROOT/'web/src/js/n2-vocabulary.js'

def build():
    book=json.loads(SOURCE.read_text())
    assert book['id']=='vocab-ja-n2-hongbao' and book['language']=='ja' and book['kind']=='vocabulary'
    words=book['words'];assert book['entryCount']==len(words)==3136
    assert len({w['id'] for w in words})==len(words)
    identities=json.loads(IDENTITIES.read_text())
    assert identities['dictionaryId']==book['id']
    assert identities['entries']==[{'sourceOrder':w['sourceOrder'],'id':w['id']} for w in words], 'N2 identities changed; content edits must preserve familiarity/memory keys'
    categories={c['id']:{s['id'] for s in c['subcategories']} for c in book['categories']}
    assert list(categories)==['1','2','3']
    for word in words:
        assert word['term'] and word['headword']==word['term'] and word['meanings']['zh-Hant']
        assert re.fullmatch(r'[ぁ-ゖァ-ヶー～〜・/]+',word['reading']),word['term']
        assert word['subcategory'] in categories[word['category']]
        assert 15<=word['sourcePage']<=294
        assert len(word['examples'])==1 and word['example']==word['examples'][0]['text']
        for example in word['examples']:
            assert example['text'] and example['text'].endswith(('。','？','！'))
            assert ''.join(s['text'] for s in example['furigana'])==example['text']
            for segment in example['furigana']:
                assert re.fullmatch(r'[ぁ-ゖァ-ヶー]*',segment['reading'])
                if re.search(r'[一-龯々]',segment['text']):assert segment['reading'],(word['term'],segment)
                if segment['reading']:assert re.fullmatch(r'[一-龯々]+',segment['text'])
    return '/* Generated by scripts/import-japanese-n2.py from the source-backed N2 snapshot. */\nwindow.MOTS_VOCABULARY_BOOKS = '+json.dumps([book],ensure_ascii=False,separators=(',',':'))+';\n'

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();data=build()
    if args.check:assert TARGET.read_text()==data,'Run scripts/import-japanese-n2.py'
    else:TARGET.write_text(data)
    print(('Verified' if args.check else 'Imported')+' 3136 N2 entries, three priorities, POS subgroups and complete example furigana.')
if __name__=='__main__':main()
